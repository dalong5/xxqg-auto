import { chromium } from 'playwright';
const b = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await b.newContext({ locale: 'zh-CN', viewport: { width: 1440, height: 900 } });
const p = await ctx.newPage();
p.on('console', (m) => { if (m.type() === 'error') console.log('CONSOLE-ERR', m.text().slice(0, 200)); });
p.on('requestfailed', (r) => console.log('FAILED', r.url().slice(0, 120), r.failure()?.errorText));
await p.goto('https://pc.xuexi.cn/points/exam-practice.html', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(6000);
const scripts = await p.evaluate(() => [...document.scripts].map((s) => s.src).filter(Boolean));
console.log('SCRIPTS', scripts.join('\n'));
console.log('nc?', await p.evaluate(() => typeof window.nc), 'AWSC?', await p.evaluate(() => typeof window.AWSC));
await b.close();