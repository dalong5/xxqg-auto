import { chromium } from 'playwright';
import { DatabaseSync } from 'node:sqlite';
const d = new DatabaseSync('data/app.db');
const jar = JSON.parse(d.prepare("select jar from logins where status='done' order by created_at desc limit 1").get().jar);
const cookies = Object.entries(jar).map(([name, value]) => ({ name, value, domain: '.xuexi.cn', path: '/' }));
const b = await chromium.launch({ channel: 'chrome', headless: true });
const ctx = await b.newContext({ locale: 'zh-CN', viewport: { width: 1440, height: 900 } });
await ctx.addCookies(cookies);
const p = await ctx.newPage();
await p.goto('https://pc.xuexi.cn/points/my-points.html', { waitUntil: 'domcontentloaded' });
await p.waitForTimeout(3000);
await p.locator('.my-points-card', { hasText: '每日答题' }).first().locator('text=去答题').first().click();
await p.waitForTimeout(4000);
console.log('url:', p.url());
console.log('tips el count:', await p.locator('.tips').count());
console.log('tip text el:', await p.locator('text=查看提示').count());
console.log('options:', await p.locator('.q-answer.choosable').count());
console.log('btn:', await p.locator('.action-row button').count(), 'disabled:', await p.locator('.action-row button').first().isDisabled().catch(() => 'n/a'));
await p.locator('.tips').first().click().catch(e => console.log('tips click err', e.message));
await p.waitForTimeout(1200);
const pop = await p.locator('.ant-popover .line-feed').count();
console.log('popover:', pop);
const html = await p.locator('.ant-popover .line-feed').first().innerHTML().catch(() => '');
console.log('tips:', [...html.matchAll(/<font[^>]*>([\s\S]*?)<\/font>/g)].map(m => m[1].trim()));
console.log('after tip click, btn disabled:', await p.locator('.action-row button').first().isDisabled().catch(() => 'n/a'));
await b.close();
